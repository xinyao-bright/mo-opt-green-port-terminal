const i18n = {
    locale: 'zh-CN',
    messages: {},
    storageKey: 'port-schedule-locale',
    staticNodes: [],
    staticAttributes: [],
    staticTitle: null,
    loadSequence: 0,

    async init() {
        this.captureStaticTranslations();
        const savedLocale = localStorage.getItem(this.storageKey) || 'zh-CN';
        await this.load(savedLocale);
        this.bindEvents();
    },

    async load(locale) {
        const sequence = ++this.loadSequence;
        if (!['zh-CN', 'en'].includes(locale)) {
            locale = 'zh-CN';
        }

        try {
            const response = await fetch(`/static/i18n/${locale}.json`);
            if (!response.ok) throw new Error('Failed to load translations');

            const messages = await response.json();
            if (sequence !== this.loadSequence) return;
            this.messages = messages;
            this.locale = locale;
            localStorage.setItem(this.storageKey, locale);

            this.updateDOM();
            this.updatePageTitle();

            const langSelector = document.getElementById('langSelector');
            if (langSelector && langSelector.value !== locale) {
                langSelector.value = locale;
            }

            document.documentElement.setAttribute('lang', locale === 'zh-CN' ? 'zh-CN' : 'en');

            window.dispatchEvent(new CustomEvent('localeChanged', { detail: { locale } }));
        } catch (error) {
            console.error('Failed to load translations:', error);
        }
    },

    t(key, fallback = null) {
        const keys = key.split('.');
        let value = this.messages;

        for (const k of keys) {
            if (value && typeof value === 'object' && k in value) {
                value = value[k];
            } else {
                return fallback || key;
            }
        }

        return typeof value === 'string' ? value : (fallback || key);
    },

    // Capture only template-authored nodes before API responses arrive. Live data is never scanned.
    captureStaticTranslations() {
        if (!document.body) return;
        const excluded = 'script,style,noscript,textarea,input,svg,[contenteditable],[data-i18n],[data-auth-zh],.auth-layout,.user-info,.ship-name-cell,.config-item-title,#configStatus,#activeConfigName,#editorTitle';
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            if (!node.parentElement || node.parentElement.closest(excluded)) continue;
            const original = node.nodeValue;
            const translated = staticUITranslations[original.trim()];
            if (translated) this.staticNodes.push({ node, zh: original, en: original.replace(original.trim(), translated), rendered: original });
        }
        document.querySelectorAll('[placeholder],[title],[aria-label]').forEach(element => {
            if (element.closest('.auth-layout,.user-info,[contenteditable]')) return;
            ['placeholder', 'title', 'aria-label'].forEach(attribute => {
                if (element.hasAttribute('data-i18n-' + attribute)) return;
                const original = element.getAttribute(attribute);
                const translated = original && staticUITranslations[original.trim()];
                if (translated) this.staticAttributes.push({ element, attribute, zh: original, en: translated, rendered: original });
            });
        });
        const title = document.title;
        if (staticUITranslations[title]) this.staticTitle = { zh: title, en: staticUITranslations[title] };
    },

    updateStaticTranslations() {
        const language = this.locale === 'en' ? 'en' : 'zh';
        this.staticNodes.forEach(entry => {
            // An application update owns the node from this point onward.
            if (!entry.node.isConnected || entry.node.nodeValue !== entry.rendered) return;
            entry.node.nodeValue = entry[language];
            entry.rendered = entry[language];
        });
        this.staticAttributes.forEach(entry => {
            if (!entry.element.isConnected || entry.element.getAttribute(entry.attribute) !== entry.rendered) return;
            entry.element.setAttribute(entry.attribute, entry[language]);
            entry.rendered = entry[language];
        });
    },

    setElementText(element, text) {
        if (!element.children.length) { element.textContent = text; return; }
        const textNodes = Array.from(element.childNodes).filter(node => node.nodeType === Node.TEXT_NODE);
        const label = textNodes.find(node => node.nodeValue.trim()) || textNodes[0];
        if (label) {
            label.nodeValue = text;
            textNodes.forEach(node => { if (node !== label) node.nodeValue = ''; });
        } else element.appendChild(document.createTextNode(text));
    },

    staticText(text) {
        return this.locale === 'en' ? (staticUITranslations[text] || text) : text;
    },

    updateDOM() {
        this.updateStaticTranslations();
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.dataset.i18n;
            const text = this.t(key);

            if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
                el.value = text;
            } else if (el.hasAttribute('placeholder')) {
                el.placeholder = text;
            } else {
                this.setElementText(el, text);
            }
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.dataset.i18nPlaceholder;
            el.placeholder = this.t(key);
        });

        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.dataset.i18nTitle;
            el.title = this.t(key);
        });
    },

    updatePageTitle() {
        if (this.staticTitle) document.title = this.staticTitle[this.locale === 'en' ? 'en' : 'zh'];
        const titleKey = document.querySelector('[data-page-title]')?.dataset.pageTitle;
        if (titleKey) {
            document.title = this.t(titleKey);
        }
    },

    bindEvents() {
        const langSelector = document.getElementById('langSelector');
        if (langSelector) {
            langSelector.addEventListener('change', (e) => {
                this.load(e.target.value);
            });
        }
    },

    formatNumber(number, decimals = 2) {
        return new Intl.NumberFormat(this.locale, {
            minimumFractionDigits: decimals,
            maximumFractionDigits: decimals
        }).format(number);
    },

    formatDate(date, options = {}) {
        const defaultOptions = {
            year: 'numeric',
            month: '2-digit',
            day: '2-digit',
            hour: '2-digit',
            minute: '2-digit'
        };
        return new Intl.DateTimeFormat(this.locale, { ...defaultOptions, ...options }).format(date);
    }
};

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => i18n.init());
} else {
    i18n.init();
}
